-- Compatibilidade com usuários que já possuíam apenas a permissão raiz antes
-- da criação dos níveis de acesso: tornam-se operadores, preservando o acesso.
INSERT INTO tb_user_role (user_id, role_id)
SELECT root_access.user_id, operator_role.id
FROM tb_user_role root_access
JOIN tb_role root_role ON root_role.id = root_access.role_id AND root_role.authority = 'ROLE_RAW_MATERIALS'
JOIN tb_role operator_role ON operator_role.authority = 'ROLE_RAW_MATERIALS_OPERATOR'
WHERE NOT EXISTS (
    SELECT 1 FROM tb_user_role access_level
    JOIN tb_role level_role ON level_role.id = access_level.role_id
    WHERE access_level.user_id = root_access.user_id
      AND level_role.authority IN ('ROLE_RAW_MATERIALS_ADMIN', 'ROLE_RAW_MATERIALS_OPERATOR', 'ROLE_RAW_MATERIALS_CONSULTATION')
);
